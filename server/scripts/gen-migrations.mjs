/**
 * Turns src/db/migrations/*.sql into a TypeScript module.
 *
 * The migration runner used to read the directory at runtime, which breaks
 * anywhere the .sql files are not shipped next to the code: `tsc` does not
 * copy them into dist/, and a bundled serverless function has no such
 * directory at all. Embedding them makes the runner work identically in dev,
 * in dist, and inside the Netlify function bundle.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const migrationsDir = path.resolve(here, "../src/db/migrations");
const target = path.resolve(here, "../src/db/migrations.generated.ts");

const files = (await readdir(migrationsDir))
  .filter((file) => file.endsWith(".sql"))
  .sort();

const entries = [];
for (const file of files) {
  const sql = await readFile(path.join(migrationsDir, file), "utf8");
  // Backticks and ${ } would break the template literal.
  const escaped = sql.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  entries.push(`  { name: ${JSON.stringify(file)}, sql: \`${escaped}\` },`);
}

const output = `// GENERATED by scripts/gen-migrations.mjs — do not edit.
// Run \`npm run gen:migrations\` (or any build/dev script) to refresh.

export interface Migration {
  name: string;
  sql: string;
}

export const migrations: Migration[] = [
${entries.join("\n")}
];
`;

await writeFile(target, output, "utf8");
console.log(`Embedded ${files.length} migrations: ${files.join(", ")}`);
